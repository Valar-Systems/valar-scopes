//
// ---- WHAT CHANGED FROM THE ORIGINALS (Apache-2.0 section 4(b)) ---------------------------------------
//  - Re-encoded from jd9365_lcd_init_cmd_t {cmd, data, data_bytes, delay_ms} into LovyanGFX's
//    Panel_DSI byte stream {1 + n, cmd, n params...}, 0-terminated. The bytes are unchanged, in order:
//    197 commands from the 720 x 720 branch, generated mechanically from the BSP source.
//  - The 800 x 800 (3.4-inch) branch is dropped.
//  - The driver's four lead-in commands are prepended, with this board's values: MADCTL 0x00 (the BSP
//    asks for RGB element order), COLMOD 0x55 (RGB565, what Panel_DSI scans out), DSI_INT0 0x01 (2 lanes).
//  - The table is split into four lists so its two delays land where the BSP puts them: LovyanGFX applies
//    getInitDelay(n) only after a whole list. List 1 is Sleep Out + 120 ms, list 2 Display On + 20 ms,
//    list 3 Tearing Effect On. The BSP sends each of 0x11, 0x29 and 0x35 with one 0x00 parameter, so
//    this does too.
//  - The driver's hardware reset (high 5 ms, low 10 ms, high 120 ms on GPIO 27) is replaced by
//    LovyanGFX's own Panel_Device reset of pin_rst, and the driver's panel-ID read (0x04) is not carried.
//  - After the lists, LovyanGFX's Panel_DSI::init_panel() writes MADCTL and COLMOD again. With
//    cfg.rgb_order = true (LGFX.h) those are 0x00 and 0x55, the values the lead-in already sent.

