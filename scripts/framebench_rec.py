# THE FRAME BENCH's replay pre-build step (docs/frame-time-bench.md, RP4 and the replay's code design), for
# env:blipscope-s3-128-framebench-replay only. The two recordings (KSFO and the survey's choice) come from UNTRACKED
# paths named by environment variables, each checked against its PINNED sha256 (RP3) before it is used, and become a
# generated header under this env's build directory (untracked: .pio/ is ignored). Nothing here prints a body, a path's
# contents or a coordinate: a refusal names the variable.
#   FRAME_BENCH_REC_A_FILE, FRAME_BENCH_REC_A_SHA   KSFO's .fbrec and its pinned sha256
#   FRAME_BENCH_REC_B_FILE, FRAME_BENCH_REC_B_SHA   the chosen airport's .fbrec and its pinned sha256
import hashlib
import json
import os
import re

Import("env")  # noqa: F821 (SCons)


def refuse(msg):
    raise SystemExit("framebench_rec.py: " + msg + "; refusing to build the replay")


def load(var_file, var_sha):
    path, want = os.environ.get(var_file, ""), os.environ.get(var_sha, "").lower()
    if not path or not os.path.isfile(path):
        refuse(f"{var_file} is unset or names no file")
    if not re.fullmatch(r"[0-9a-f]{64}", want):
        refuse(f"{var_sha} is unset or not a sha256")
    blob = open(path, "rb").read()
    if hashlib.sha256(blob).hexdigest() != want:
        refuse(f"the file {var_file} names is not the pinned recording ({var_sha})")
    polls = [json.loads(l) for l in blob.decode("utf-8").splitlines() if l.strip()]
    for p in polls:
        if not (isinstance(p.get("seq"), int) and isinstance(p.get("ms"), int) and isinstance(p.get("epoch"), int)
                and isinstance(p.get("body"), str) and ")FBR\"" not in p["body"]):
            refuse(f"{var_file}: a poll is not {{seq, ms, epoch, body}}")
    return polls


recs = [load("FRAME_BENCH_REC_A_FILE", "FRAME_BENCH_REC_A_SHA"), load("FRAME_BENCH_REC_B_FILE", "FRAME_BENCH_REC_B_SHA")]
gen = os.path.join(env.subst("$BUILD_DIR"), "fbrec")  # noqa: F821
os.makedirs(gen, exist_ok=True)
lines = ["// GENERATED by scripts/framebench_rec.py from the two PINNED recordings: never edited, never tracked.",
         "#pragma once", "// included INSIDE namespace framebench (FrameBench.h): no namespace of its own",
         "struct RecPoll { int seq; uint32_t ms; long epoch; const char* body; };"]
for i, polls in enumerate(recs):
    lines.append(f"static const RecPoll kRec{i}[] = {{")
    for p in polls:
        lines.append(f'    {{{p["seq"]}, {p["ms"]}u, {p["epoch"]}L, R"FBR({p["body"]})FBR"}},')
    lines.append("};")
lines += ["static const RecPoll* const kRecPolls[2] = {kRec0, kRec1};",
          f"static const int kRecN[2] = {{{len(recs[0])}, {len(recs[1])}}};", ""]
open(os.path.join(gen, "framebench_rec_gen.h"), "w", encoding="utf-8", newline="\n").write("\n".join(lines))
env.Append(CPPPATH=[gen])  # noqa: F821
