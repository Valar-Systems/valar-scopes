#!/usr/bin/env python3
"""The OTA identity record, from the offering side (docs/weatherscope-stage3.md section 3, A12.103, A12.104).

    python3 scripts/check_ota_identity.py <env> <firmware.bin> [--slug S --manifest M]   one built image (every CI row)
    python3 scripts/check_ota_identity.py --fleet           O5 + Q76 over skus.yml and the resolved config
    python3 scripts/check_ota_identity.py --fleet-sabotage  each fleet rule must refuse a planted copy of the real config
    python3 scripts/check_ota_identity.py --check-table     test/fixtures/ota/identities.txt equals what the fleet derives
    python3 scripts/check_ota_identity.py --emit-table      rewrite that table from the fleet
    python3 scripts/check_ota_identity.py --extract-head <firmware.bin> <out.head.bin>   the first 352 bytes (host fixtures)
    python3 scripts/check_ota_identity.py --selftest
    python3 scripts/check_ota_identity.py --check-wiring

WHAT A DEVICE CHECKS (include/OtaIdentity.h): every image carries a 64-byte record at file offset 0x120 naming its board
(variant::SLUG) and its scope (FW_OTA_PREFIX), and a device installs an image only if it is exactly what the device asked
for -- its own board, and the scope in its request. This script is the OTHER side: nothing is published under a name its
record contradicts, so a mislabel is refused before upload rather than discovered by the fleet.

THE IMAGE MODE, on every build row (no `if:`), before the upload and the receipt:
  - the record must equal the env's identity, derived from `pio project config` (the scope from its FW_OTA_PREFIX
    define, the board from its BLIPSCOPE_VARIANT_* flag through include/variants/Variant.h to that header's SLUG);
  - the record must be present exactly when the image carries LogOtaSlot's "[ota-slot] " string, which is what reads
    it (and so keeps it linked): an env with no OTA path must read no-record, and one with it must carry a record;
  - on a slug-ful row, the record's scope + board must equal the slug AND the flash manifest's slug (O4 (i)).

THE FLEET MODE (O5, Q76), no build needed:
  - every slug-ful row's slug equals its env's FW_OTA_PREFIX + variant::SLUG;
  - every skus.yml env of one board names one partition table, flash size and memory type. An OTA writes the app only,
    so a device keeps the table it was flashed with, and any scope's image for that board must fit it.

Exit: 0 pass, 1 FAIL, 2 BLIND (cannot read the image, the config or the variants; never a pass).
"""
