STEP_NAME = "OTA identity in the image"
MANIFEST_STEP = "Factory image, flash manifest and region files"

OFFSET, SIZE = 0x120, 64
HEAD = OFFSET + SIZE
MAGIC = bytes([0x56, 0x53, 0x49, 0x44])   # "VSID"
FIELD = 24
ANCHOR = b"[build] env="
SLOT_STRING = b"[ota-slot] "
SLUG_RE = re.compile(r"^[a-z0-9-]*$")
TABLE_HEADER = ("# OTA identities of every skus.yml env that compiles src/OtaUpdater.cpp: env, scope (- for none), board.\n"
                "# Generated by scripts/check_ota_identity.py --emit-table; CI's --check-table holds it equal to the fleet.\n")


class Blind(Exception):
    pass


# ---------------------------------------------------------------------------------------------------------- the record

def parse_record(data):
    """(verdict, scope, board) from an image's bytes: verdict is ok / no-record / bad-record / short."""
    if len(data) < HEAD:
        return "short", None, None
    r = data[OFFSET:HEAD]
    if r[:4] != MAGIC:
        return "no-record", None, None
    if r[4] != 1 or r[5] != SIZE:
        return "bad-record", None, None
    bl, sl = r[6], r[7]
    if bl == 0 or bl > FIELD or sl > FIELD:
        return "bad-record", None, None
    board, scope = r[8:8 + FIELD], r[8 + FIELD:8 + 2 * FIELD]
    for field, n in ((board, bl), (scope, sl)):
        if any(b != 0 for b in field[n:]):
            return "bad-record", None, None
        if not SLUG_RE.match(field[:n].decode("ascii", "replace")):
            return "bad-record", None, None
    if any(r[8 + 2 * FIELD:]):
        return "bad-record", None, None
    return "ok", scope[:sl].decode("ascii"), board[:bl].decode("ascii")


def classify_image(data, want_scope, want_board, slug=None, manifest_slug=None):
    """(verdict, reasons) for one image against its env's derived identity. verdict: PASS / FAIL / BLIND."""
    if ANCHOR not in data:
        return "BLIND", ['no "[build] env=" anchor: this file cannot be read as an image']
    verdict, scope, board = parse_record(data)
    has_slot = SLOT_STRING in data
    want = want_scope + want_board
    reasons = []
    if has_slot and verdict != "ok":
        reasons.append("the image carries LogOtaSlot (an OTA path) but its record reads %s" % verdict)
    if not has_slot and verdict != "no-record":
        reasons.append("the image has no OTA path (no LogOtaSlot) but its record reads %s" % verdict)
    if verdict == "ok":
        got = scope + board
        if (scope, board) != (want_scope, want_board):
            reasons.append("the record says %s (scope %r, board %r); this env is %s (scope %r, board %r)"
                           % (got, scope, board, want, want_scope, want_board))
        if slug is not None and got != slug:
            reasons.append("the record says %s; it would be published as firmware-%s.bin" % (got, slug))
        if manifest_slug is not None and manifest_slug != slug:
            reasons.append("the flash manifest says slug %r; it would be published as %r" % (manifest_slug, slug))
    elif slug is not None:
        reasons.append("a slug-ful row (firmware-%s.bin) must carry a record; it reads %s" % (slug, verdict))
    if reasons:
        return "FAIL", reasons
    if verdict == "ok":
        return "PASS", ["record %s (scope %r, board %r) at 0x%x" % (want, want_scope, want_board, OFFSET)
                        + (", the slug agrees" if slug is not None else "")
                        + (", the manifest agrees" if manifest_slug is not None else "")]
    return "PASS", ["no OTA path and no record, as expected"]


# ---------------------------------------------------------------------------------------------------------- the fleet

def pio_config(project_dir):
    """{env: {key: value}} from `pio project config --json-output`, which resolves extends and ${...}."""
    try:
        out = subprocess.run(["pio", "project", "config", "--json-output", "-d", project_dir],
                             capture_output=True, text=True, timeout=180)
    except (OSError, subprocess.TimeoutExpired) as e:
        raise Blind("cannot run `pio project config`: %s" % e)
    if out.returncode != 0:
        raise Blind("`pio project config` exited %d: %s" % (out.returncode, out.stderr.strip()[:300]))
    m = re.search(r"\[\s*\[", out.stdout)
    if not m:
        raise Blind("`pio project config` printed no JSON")
    envs = {}
    for section, items in json.loads(out.stdout[m.start():]):
        if section.startswith("env:"):
            envs[section[4:]] = {k: v for k, v in items}
    return envs


def flags_of(cfg):
    v = cfg.get("build_flags", [])
    return " ".join(v) if isinstance(v, list) else str(v)


def scope_of(flags):
    found = re.findall(r'-DFW_OTA_PREFIX=\\?"([^"\\]*)\\?"', flags)
    if len(found) > 1:
        raise Blind("FW_OTA_PREFIX defined %d times" % len(found))
    return found[0] if found else ""


def variants(root):
    """{BLIPSCOPE_VARIANT_X: slug}, read from Variant.h's #if chain and each header's SLUG."""
    try:
        chain = open(os.path.join(root, "include", "variants", "Variant.h"), encoding="utf-8").read()
    except OSError as e:
        raise Blind("cannot read Variant.h: %s" % e)
    out = {}
    for define, header in re.findall(r'defined\((BLIPSCOPE_VARIANT_\w+)\)\s*\n\s*#include\s+"([^"]+)"', chain):
        try:
            text = open(os.path.join(root, "include", header), encoding="utf-8").read()
        except OSError as e:
            raise Blind("cannot read %s: %s" % (header, e))
        slugs = re.findall(r'constexpr\s+char\s+SLUG\[\]\s*=\s*"([^"]+)"', text)
        if len(slugs) != 1:
            raise Blind("%s: expected one SLUG, found %d" % (header, len(slugs)))
        out[define] = slugs[0]
    if not out:
        raise Blind("no variant found in Variant.h")
    return out


def board_of(flags, table):
    found = sorted(set(re.findall(r"-D(BLIPSCOPE_VARIANT_\w+)", flags)) & set(table))
    if len(found) != 1:
        raise Blind("expected one known BLIPSCOPE_VARIANT_* flag, found %s" % (found or "none"))
    return table[found[0]]


def compiles(cfg, path):
    """Whether the env's resolved build_src_filter selects `path` (relative to src/). Ordered +/- patterns."""
    v = cfg.get("build_src_filter", ["+<*> -<.git/> -<.svn/>"])
    text = " ".join(v) if isinstance(v, list) else str(v)
    selected = False
    for sign, pat in re.findall(r"([+-])<([^>]*)>", text):
        hit = path.startswith(pat) if pat.endswith("/") else fnmatch.fnmatchcase(path, pat)
        if hit:
            selected = sign == "+"
    return selected


def derive(root, skus_path):
    """[(row, scope, board, cfg)] for every skus.yml row, from the resolved config."""
    rows = skus.load(skus_path)
    cfg = pio_config(root)
    table = variants(root)
    out = []
    for r in rows:
        if r["env"] not in cfg:
            raise Blind("skus.yml env %s is not in the resolved config" % r["env"])
        c = cfg[r["env"]]
        f = flags_of(c)
        out.append((r, scope_of(f), board_of(f, table), c))
    return out


def built(derived):
    """The rows CI builds: a `status: retired` row is not built (skus.yml, A12.105), so it has no image to check
    and its partition table is no fleet's."""
    return [d for d in derived if d[0].get("status") != "retired"]


def fleet_problems(derived):
    """[(rule, text)]: O5 per slug-ful row, Q76 per board and field -- over the built rows only."""
    derived = built(derived)
    problems = []
    for r, scope, board, _ in derived:
        if r["slug"] and r["slug"] != scope + board:
            problems.append(("O5", "%s: slug %s, but its identity is %s (scope %r + board %r)"
                             % (r["env"], r["slug"], scope + board, scope, board)))
    by_board = {}
    for r, _, board, c in derived:
        by_board.setdefault(board, []).append((r["env"], c))
    for board in sorted(by_board):
        for key in ("board_build.partitions", "board_build.flash_size", "board_build.arduino.memory_type"):
            seen = {}
            for env, c in by_board[board]:
                seen.setdefault(str(c.get(key)), []).append(env)
            if len(seen) > 1:
                problems.append(("Q76", "board %s: %s differs -- %s" % (
                    board, key, "; ".join("%s: %s" % (v, ", ".join(es)) for v, es in sorted(seen.items())))))
    return problems


def table_text(derived):
    lines = ["%s %s %s" % (r["env"], scope or "-", board) for r, scope, board, c in built(derived)
             if compiles(c, "OtaUpdater.cpp")]
    return TABLE_HEADER + "\n".join(lines) + "\n"


def run_fleet(root=ROOT, skus_path=skus.DEFAULT, quiet=False):
    derived = derive(root, skus_path)
    problems = fleet_problems(derived)
    if not quiet:
        boards, live = {}, built(derived)
        for r, _, board, _ in live:
            boards[board] = boards.get(board, 0) + 1
        print("fleet: %d built skus.yml env(s) (%d retired, skipped); slug-ful %d; boards %s"
              % (len(live), len(derived) - len(live), sum(1 for r, _, _, _ in live if r["slug"]),
                 ", ".join("%s %d" % (b, n) for b, n in sorted(boards.items()))))
        for rule, text in problems:
            print("  FAIL %s %s" % (rule, text))
    return problems


# ---------------------------------------------------------------------------------------------------------- sabotage

SABOTAGES = {
    # name: (file, section or None, anchor, replacement, the one rule it must trip)
    "S-O5": ("skus.yml", None,
             "- { env: blipscope-s3-128, status: shipping, slug: s3-128 }",
             "- { env: blipscope-s3-128, status: shipping, slug: eam-s3-128 }", "O5"),
    "S-Q76": ("platformio.ini", "[env:weatherscope-s3-128]",
              "board_build.partitions = partitions-s3-16mb-bignvs.csv",
              "board_build.partitions = default_16MB.csv", "Q76"),
}


def plant(text, section, anchor, repl):
    if section is None:
        assert text.count(anchor) == 1, "anchor found %d times, need exactly 1" % text.count(anchor)
        out = text.replace(anchor, repl)
    else:
        start = text.index(section + "\n")
        m = re.search(r"^\[", text[start + 1:], re.M)
        end = start + 1 + m.start() if m else len(text)
        body = text[start:end]
        assert body.count(anchor) == 1, "anchor found %d times in %s, need exactly 1" % (body.count(anchor), section)
        out = text[:start] + body.replace(anchor, repl) + text[end:]
    assert out != text, "the plant did not change the file"
    return out


def fleet_sabotage():
    ok = True
    for name, (fname, section, anchor, repl, rule) in SABOTAGES.items():
        with tempfile.TemporaryDirectory() as td:
            shutil.copy(os.path.join(ROOT, "platformio.ini"), td)
            shutil.copy(os.path.join(ROOT, "skus.yml"), td)
            shutil.copytree(os.path.join(ROOT, "include", "variants"), os.path.join(td, "include", "variants"))
            p = os.path.join(td, fname)
            text = open(p, encoding="utf-8").read()
            open(p, "w", encoding="utf-8", newline="\n").write(plant(text, section, anchor, repl))
            problems = run_fleet(td, os.path.join(td, "skus.yml"), quiet=True)
        good = len(problems) == 1 and problems[0][0] == rule
        ok &= good
        print("  %s %s: %d problem(s) %s (want exactly one %s)" % ("ok  " if good else "FAIL", name, len(problems),
                                                               [p[0] for p in problems], rule))
        for _, text in problems:
            print("        " + text)
    clean = run_fleet(quiet=True)
    print("  %s unplanted: %d problem(s)" % ("ok  " if not clean else "FAIL", len(clean)))
    ok &= not clean
    print("fleet-sabotage " + ("PASSED" if ok else "FAILED"))
    return 0 if ok else 1


# ---------------------------------------------------------------------------------------------------------- wiring

def check_wiring(text):
    """Problems with where the image step sits in the build job ([] = good). None = cannot find the job."""
    m = re.search(r"^  build:\n(.*?)(?=^  [a-z][a-z0-9_-]*:\n|\Z)", text, re.M | re.S)
    if not m:
        return None
    steps = re.split(r"^      - ", m.group(1), flags=re.M)[1:]
    names = [re.match(r"name:\s*(.*)", s).group(1).strip() if re.match(r"name:", s) else "" for s in steps]
    idx = [i for i, n in enumerate(names) if n.startswith(STEP_NAME)]
    if len(idx) != 1:
        return ["expected exactly one '%s' step in the build job, found %d" % (STEP_NAME, len(idx))]
    i = idx[0]
    problems = []
    if re.search(r"^        if:", steps[i], re.M):
        problems.append("the step has an `if:`; it must run for every skus.yml row")
    if "scripts/check_ota_identity.py" not in steps[i]:
        problems.append("the step does not run scripts/check_ota_identity.py")
    j = [k for k, n in enumerate(names) if n.startswith(MANIFEST_STEP)]
    if len(j) != 1:
        problems.append("expected exactly one '%s' step, found %d" % (MANIFEST_STEP, len(j)))
    elif j[0] > i:
        problems.append("the step runs before '%s', whose manifest it reads" % MANIFEST_STEP)
    for later in ("Attach to release", "Publication receipt"):
        k = [x for x, n in enumerate(names) if n.startswith(later)]
        if len(k) != 1:
            problems.append("expected exactly one '%s' step, found %d" % (later, len(k)))
        elif k[0] < i:
            problems.append("the step runs after '%s'; a FAIL must stop the upload and the receipt" % later)
    return problems


# ---------------------------------------------------------------------------------------------------------- selftest

def selftest():
    def record(board, scope, magic=MAGIC, version=1, length=SIZE, bl=None, sl=None, pad=b"", reserved=0):
        r = bytearray(SIZE)
        r[0:4] = magic
        r[4], r[5] = version, length
        r[6] = len(board) if bl is None else bl
        r[7] = len(scope) if sl is None else sl
        r[8:8 + len(board)] = board.encode()
        r[8 + FIELD:8 + FIELD + len(scope)] = scope.encode()
        if pad:
            r[8 + len(board)] = pad[0]
        r[63] = reserved
        return bytes(r)

    def img(rec=None, slot=True, anchor=True):
        head = bytearray(b"\xe9" + b"\x00" * (OFFSET - 1))
        body = (rec if rec is not None else b"C:/Users/x/.platformio/packages/framework-arduinoespressif32/cores/esp32/a")
        tail = (ANCHOR + b"blipscope-s3-128\0" if anchor else b"\0") + (SLOT_STRING + b"%s running=\0" if slot else b"\0")
        return bytes(head) + body + tail

    good = record("s3-128", "")
    cases = [
        # (name, data, want scope, want board, slug, manifest slug, verdict)
        ("its own record", img(good), "", "s3-128", None, None, "PASS"),
        ("slug-ful, slug and manifest agree", img(good), "", "s3-128", "s3-128", "s3-128", "PASS"),
        ("O4 (i): another scope's image under this slug", img(record("s3-128", "weatherscope-")), "weatherscope-",
         "s3-128", "s3-128", "s3-128", "FAIL"),
        ("the record disagrees with the env", img(record("s3-146", "")), "", "s3-128", None, None, "FAIL"),
        ("the manifest's slug disagrees", img(good), "", "s3-128", "s3-128", "eam-s3-128", "FAIL"),
        ("an OTA path with no record", img(None), "", "s3-128", None, None, "FAIL"),
        ("a record with no OTA path", img(good, slot=False), "", "s3-128", None, None, "FAIL"),
        ("no OTA path, no record", img(None, slot=False), "", "s3-128", None, None, "PASS"),
        ("slug-ful with no record", img(None, slot=False), "", "s3-128", "s3-128", "s3-128", "FAIL"),
        ("a record version this does not know", img(record("s3-128", "", version=2)), "", "s3-128", None, None, "FAIL"),
        ("no anchor", img(good, anchor=False), "", "s3-128", None, None, "BLIND"),
    ]
    ok = True
    for name, data, ws, wb, slug, mslug, want in cases:
        got, _ = classify_image(data, ws, wb, slug, mslug)
        g = got == want
        ok &= g
        print("  %s image: %-48s want %-5s got %s" % ("ok  " if g else "FAIL", name, want, got))

    parse_cases = [
        ("a good record", good, "ok"),
        ("a wrong magic", record("s3-128", "", magic=b"WXC1"), "no-record"),
        ("length 63", record("s3-128", "", length=63), "bad-record"),
        ("a board length of 0", record("s3-128", "", bl=0), "bad-record"),
        ("a scope length of 25", record("s3-128", "", sl=25), "bad-record"),
        ("an upper-case byte", record("S3-128", ""), "bad-record"),
        ("a byte after the board's length", record("s3-128", "", pad=b"x"), "bad-record"),
        ("a reserved byte", record("s3-128", "", reserved=1), "bad-record"),
    ]
    for name, rec, want in parse_cases:
        got = parse_record(b"\xe9" + b"\0" * (OFFSET - 1) + rec)[0]
        g = got == want
        ok &= g
        print("  %s parse: %-46s want %-10s got %s" % ("ok  " if g else "FAIL", name, want, got))

    def cfg(scope, variant, parts="p.csv", size="16MB", mem="qio_opi", filt=None):
        c = {"build_flags": ["-DBLIPSCOPE_VARIANT_%s" % variant] + (['-DFW_OTA_PREFIX=\\"%s\\"' % scope] if scope else []),
             "board_build.partitions": parts, "board_build.flash_size": size, "board_build.arduino.memory_type": mem}
        if filt is not None:
            c["build_src_filter"] = [filt]
        return c

    vt = {"BLIPSCOPE_VARIANT_S3_128": "s3-128", "BLIPSCOPE_VARIANT_S3_146": "s3-146"}

    def fleet(rows):
        d = []
        for row in rows:
            env, slug, c = row[:3]
            f = flags_of(c)
            d.append(({"env": env, "slug": slug, "status": row[3] if len(row) > 3 else "build-only"},
                      scope_of(f), board_of(f, vt), c))
        return [p[0] for p in fleet_problems(d)]

    base = [("blipscope-s3-128", "s3-128", cfg("", "S3_128")), ("weatherscope-s3-128", None, cfg("weatherscope-", "S3_128")),
            ("blipscope-s3-146", None, cfg("", "S3_146", parts="d.csv"))]
    fleet_cases = [
        ("the fleet as it is", base, []),
        ("O5: a slug that is another scope's name", [("blipscope-s3-128", "eam-s3-128", cfg("", "S3_128"))] + base[1:], ["O5"]),
        ("Q76: one s3-128 env on another table", base[:1] + [("weatherscope-s3-128", None, cfg("weatherscope-", "S3_128",
                                                                                                parts="d.csv"))] + base[2:], ["Q76"]),
        ("Q76: another flash size", base[:1] + [("weatherscope-s3-128", None, cfg("weatherscope-", "S3_128",
                                                                                   size="8MB"))] + base[2:], ["Q76"]),
        ("Q76: another memory type", base[:1] + [("weatherscope-s3-128", None, cfg("weatherscope-", "S3_128",
                                                                                    mem="qio_qspi"))] + base[2:], ["Q76"]),
        ("two boards may differ", base, []),
        ("a retired env on another table is skipped", base + [("gone-s3-128", None, cfg("", "S3_128", parts="d.csv"),
                                                               "retired")], []),
    ]
    for name, rows, want in fleet_cases:
        got = fleet(rows)
        g = got == want
        ok &= g
        print("  %s fleet: %-46s want %-8s got %s" % ("ok  " if g else "FAIL", name, want, got))

    filt_cases = [
        ("the default filter", cfg("", "S3_128"), True),
        ("an edition filter", cfg("", "S3_128", filt="+<*> -<eam/> -<hwtest_main.cpp> +<weatherscope/>"), True),
        ("a -<*> filter", cfg("", "S3_128", filt="-<*> +<weatherscope/bench/>"), False),
        ("a file filter", cfg("", "S3_128", filt="+<probe/TouchProbe.cpp>"), False),
        ("excluded by name", cfg("", "S3_128", filt="+<*> -<OtaUpdater.cpp>"), False),
    ]
    for name, c, want in filt_cases:
        got = compiles(c, "OtaUpdater.cpp")
        g = got == want
        ok &= g
        print("  %s filter: %-45s want %-5s got %s" % ("ok  " if g else "FAIL", name, want, got))

    def step(name, extra=""):
        return "      - name: %s\n%s        run: x\n" % (name, extra)

    def wf(*steps):
        return "jobs:\n  build:\n    steps:\n" + "".join(steps) + "  version:\n    steps:\n"

    ours = step(STEP_NAME + " (${{ matrix.env }})").replace("run: x", "run: python3 scripts/check_ota_identity.py x")
    man, attach, receipt = step(MANIFEST_STEP), step("Attach to release"), step("Publication receipt")
    wiring = [
        ("after the manifest, before the upload", wf(man, ours, attach, receipt), True),
        ("before the manifest it reads", wf(ours, man, attach, receipt), False),
        ("after the upload", wf(man, attach, ours, receipt), False),
        ("gated to slug-ful rows", wf(man, ours.replace("        run:", "        if: matrix.slug\n        run:"), attach,
                                       receipt), False),
        ("missing", wf(man, attach, receipt), False),
    ]
    for name, text, want_ok in wiring:
        got_ok = check_wiring(text) == []
        g = got_ok == want_ok
        ok &= g
        print("  %s wiring: %-44s want %-7s got %s" % ("ok  " if g else "FAIL", name, "ok" if want_ok else "refused",
                                                     "ok" if got_ok else "refused"))
    print("selftest " + ("PASSED" if ok else "FAILED"))
    return 0 if ok else 1


