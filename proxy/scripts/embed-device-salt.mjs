#!/usr/bin/env node
/**
 * embed-device-salt.mjs -- the firmware's LEADERBOARD_SALT, as a module the Worker
 * can read.
 *
 * The device id is SHA-256(raw MAC || LEADERBOARD_SALT)[:8], computed ON-DEVICE
 * from the #define in include/DeviceIdentity.h. The provisioning route
 * (src/provision.ts) takes a MAC and must derive the SAME id, so it needs the same
 * salt. Copying the string by hand would be a second copy that drifts silently --
 * every minted key would then belong to an id no board ever reports. So the Worker's
 * copy is GENERATED from the header, and CI runs --check.
 *
 * (The bench recomputes the id from the MAC too and refuses a mismatch with what the
 * Worker returns: the runtime half of the same check.)
 *
 *   node scripts/embed-device-salt.mjs           regenerate
 *   node scripts/embed-device-salt.mjs --check   fail if the generated file is stale (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "..", "..", "include", "DeviceIdentity.h");
const OUT = join(HERE, "..", "src", "devicesalt.generated.ts");

const header = readFileSync(SRC, "utf8");
const m = header.match(/#\s*define\s+LEADERBOARD_SALT\s+"([^"]+)"/g) ?? [];
if (m.length !== 1) {
  console.error(`embed-device-salt: expected exactly one LEADERBOARD_SALT #define in ${SRC}, found ${m.length}`);
  process.exit(2);
}
const salt = m[0].match(/"([^"]+)"/)[1];

const body =
  "// GENERATED by scripts/embed-device-salt.mjs from include/DeviceIdentity.h.\n" +
  "// Do not edit by hand; run `node scripts/embed-device-salt.mjs`. CI runs --check.\n" +
  `export const LEADERBOARD_SALT = ${JSON.stringify(salt)};\n`;

if (process.argv.includes("--check")) {
  let cur = "";
  try { cur = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing = stale */ }
  if (cur !== body) {
    console.error("src/devicesalt.generated.ts is stale -- run: node scripts/embed-device-salt.mjs");
    process.exit(1);
  }
  console.log("devicesalt.generated.ts matches include/DeviceIdentity.h");
} else {
  writeFileSync(OUT, body);
  console.log(`wrote ${OUT}`);
}
