"""3.5c's stored record as C++ (docs/weatherscope-stage3.md A12.144): test/fixtures/wx/nws/dallas-day.json becomes
src/weatherscope/WxForecastData.h, which StoredFeeds.cpp serves and test_wx_swipe.cpp reads, so the K rows run on the
device's own data. It keeps what the screens read: 24 hourly entries (the record holds 48 for later cases), every period,
the observation, and the SYNTHETIC alert list, plus the capture's own (empty) list.

test/fixtures/wx/nws/dallas-night.json becomes test/host/wx_nws_night.h (A12.167), the suite's second stored case: its
periods, its capture time and its observation, which is all ComposeConditions reads. It sits under test/host/ so that no
firmware build can reach it: the image serves the day case and nothing else.

    python -I tools/weatherscope/nws/emit_nws.py           writes both headers
    python -I tools/weatherscope/nws/emit_nws.py --check   the headers on disk are what this would write

Prints counts only. Exit 0 written or matching; 1 stale; 2 the rig.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
DAY = os.path.join(ROOT, "test", "fixtures", "wx", "nws", "dallas-day.json")
OUT = os.path.join(ROOT, "src", "weatherscope", "WxForecastData.h")
NIGHT = os.path.join(ROOT, "test", "fixtures", "wx", "nws", "dallas-night.json")
NIGHT_OUT = os.path.join(ROOT, "test", "host", "wx_nws_night.h")
OFFSET_MIN = -360   # CST, read from the capture's first hourly entry; fixed per stored case (A12.133)
HOURS = 24


def cstr(s):
    assert all(32 <= ord(c) < 127 and c not in '"\\' for c in s), "a stored string must be plain ASCII"
    return '"%s"' % s


def b(v):
    return "true" if v else "false"


def periods(r):
    lines = [f"constexpr wx::Period kPeriods[{len(r['periods'])}] = {{"]
    for p in r["periods"]:
        lines.append(f"    {{{cstr(p['name'])}, {p['startUtc']}, {b(p['isDaytime'])}, {p['tempF']}, {b(p['hasTemp'])}, "
                     f"{p['pop']}, {b(p['hasPop'])}, {cstr(p['short'])}}},")
    return lines + ["};"]


def observation(o, name):
    return [f"inline wx::Observation {name}()", "{", "    wx::Observation o;", "    o.valid = true;",
            f"    o.timeUtc = {o['timeUtc']};", f"    o.hasTempF = {b(o['hasTemp'])};", f"    o.tempF = {o['tempF']};",
            f"    o.hasWind = {b(o['hasWind'])};", f"    o.windMph = {o['windMph']};",
            f"    o.hasWindDir = {b(o['hasWindDir'])};", f"    o.windDirDeg = {o['windDirDeg']};",
            f"    o.hasGust = {b(o['hasGust'])};", f"    o.gustMph = {o['gustMph']};",
            f"    o.hasHumidity = {b(o['hasHumidity'])};", f"    o.humidityPct = {o['humidityPct']};",
            "    return o;", "}"]


def text():
    r = json.load(open(DAY, encoding="utf-8"))
    lines = ["// GENERATED by tools/weatherscope/nws/emit_nws.py from test/fixtures/wx/nws/dallas-day.json: do not edit.",
             "// " + r["source"] + ". run.sh runs its --check. The alert list here is SYNTHETIC, labelled so in the record:",
             "// the capture held no watch or advisory (A12.130).",
             "#pragma once", "", '#include "WxFeeds.h"', "", "namespace wxnws {", "",
             f"constexpr int64_t kCapturedUtc = {r['capturedUtc']};",
             f"constexpr int kOffsetMin = {OFFSET_MIN};", "",
             f"constexpr wx::Hour kHours[{HOURS}] = {{"]
    for h in r["hourly"][:HOURS]:
        lines.append(f"    {{{h['startUtc']}, {h['tempF']}, {h['pop']}, {b(h['hasTemp'])}, {b(h['hasPop'])}}},")
    items = r["syntheticAlerts"]["items"]
    lines += ["};", ""] + periods(r) + [""] + observation(r["observation"], "DayObservation")
    lines += ["", "inline const wx::Alert* SyntheticAlerts(size_t* count)", "{", f"    static wx::Alert items[{len(items)}];"]
    for i, a in enumerate(items):
        lines.append(f"    items[{i}].event = {cstr(a['event'])};")
        lines.append(f"    items[{i}].startUtc = {a['startUtc']};")
        lines.append(f"    items[{i}].expiresUtc = {a['endUtc']};")
    lines += [f"    *count = {len(items)};", "    return items;", "}", "", "}  // namespace wxnws", ""]
    return "\n".join(lines), len(r["hourly"][:HOURS]), len(r["periods"]), len(items)


def night_text():
    r = json.load(open(NIGHT, encoding="utf-8"))
    lines = ["// GENERATED by tools/weatherscope/nws/emit_nws.py from test/fixtures/wx/nws/dallas-night.json: do not edit.",
             "// " + r["source"] + ". run.sh runs its --check. The host suite's second stored case (A12.167): the",
             "// image serves the day case and nothing else.",
             "#pragma once", "", '#include "WxFeeds.h"', "", "namespace wxnight {", "",
             f"constexpr int64_t kCapturedUtc = {r['capturedUtc']};", ""]
    lines += periods(r) + [""] + observation(r["observation"], "NightObservation") + ["", "}  // namespace wxnight", ""]
    return "\n".join(lines), len(r["periods"])


def main(argv):
    try:
        want, nh, np, na = text()
        night, nn = night_text()
    except (OSError, KeyError, ValueError, AssertionError) as e:
        print(f"emit_nws: the rig: {type(e).__name__}: {e}")
        return 2
    bad = False
    for path, body, what in ((OUT, want, f"{nh} hours, {np} periods, {na} alerts"), (NIGHT_OUT, night, f"{nn} periods")):
        name = os.path.basename(path)
        if "--check" not in argv:
            open(path, "w", encoding="utf-8", newline="\n").write(body)
            print(f"wrote {name}: {what}")
            continue
        try:
            have = open(path, encoding="utf-8").read().replace("\r\n", "\n")
        except OSError:
            print(f"emit_nws: {name} cannot be read")
            bad = True
            continue
        ok = have == body
        print(f"{name}: {what}, {'as the record says' if ok else 'STALE'}")
        bad |= not ok
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
